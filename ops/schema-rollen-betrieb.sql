create or replace function ops_tickets_status_stamp()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if new.status in ('geloest','geschlossen') and (tg_op = 'INSERT' or old.status not in ('geloest','geschlossen')) then
    new.geloest_at = now();
  elsif new.status not in ('geloest','geschlossen') then
    new.geloest_at = null;
  end if;
  if tg_op = 'UPDATE' and new.status is distinct from old.status then
    insert into ops_ticket_eintraege (ticket_id, art, text, created_by)
    values (new.id, 'status', old.status || ' → ' || new.status, auth.uid());
  end if;
  return new;
end $$;
drop trigger if exists ops_tickets_status_stamp on ops_tickets;
create trigger ops_tickets_status_stamp before insert or update on ops_tickets
for each row execute function ops_tickets_status_stamp();

