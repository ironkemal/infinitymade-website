create table if not exists ops_wartung (
  id                 uuid primary key default gen_random_uuid(),
  box_id             uuid not null references ops_boxen(id) on delete cascade,
  ticket_id          uuid,                 -- FK unten, nach ops_tickets
  datum              date not null default current_date,
  art                text not null default 'fernwartung'
                       check (art in ('installation','update','backup_pruefung','fernwartung','vor_ort','reparatur','hardwaretausch','sonstiges')),
  beschreibung       text not null default '',
  ergebnis           text not null default 'erledigt' check (ergebnis in ('erledigt','teilweise','fehlgeschlagen')),
  dauer_min          integer check (dauer_min is null or dauer_min >= 0),
  runbook_id         uuid references ops_wissen(id) on delete set null,
  durchgefuehrt_von  uuid references ops_members(id) on delete set null,
  created_at         timestamptz not null default now()
);
create index if not exists ops_wartung_box_idx on ops_wartung (box_id, datum desc);

create or replace function ops_wartung_touch_box()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  update ops_boxen
     set letzte_wartung = greatest(coalesce(letzte_wartung, new.datum), new.datum),
         backup_geprueft_am = case when new.art = 'backup_pruefung' and new.ergebnis = 'erledigt'
                                   then greatest(coalesce(backup_geprueft_am, new.datum), new.datum)
                                   else backup_geprueft_am end
   where id = new.box_id;
  return new;
end $$;
drop trigger if exists ops_wartung_touch_box on ops_wartung;
create trigger ops_wartung_touch_box after insert on ops_wartung
for each row execute function ops_wartung_touch_box();

