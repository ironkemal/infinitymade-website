-- ── 5. RLS-Matrix ──────────────────────────────────────────────────────────
-- (Tabelle, Leserollen, Schreibrollen [insert/update], Löschrollen). admin implizit.
-- Bestehende Policies der Tabelle werden vollständig ersetzt.
do $$
declare
  m record;
  p record;
  rd text; wr text; dl text;
begin
  for m in
    select * from (values
      ('ops_todos',               '{vertrieb,technik,support}',      '{vertrieb,technik,support}', '{technik}'),
      ('ops_todos_audit',         '{vertrieb,technik,support}',      '{}',                          '{}'),
      ('ops_wissen',              '{vertrieb,technik,support}',      '{vertrieb,technik,support}', '{technik}'),
      ('ops_decisions',           '{technik}',                       '{}',                          '{}'),
      ('ops_meetings',            '{}',                              '{}',                          '{}'),
      ('ops_finance_expenses',    '{buchhaltung}',                   '{}',                          '{}'),
      ('ops_finance_audit_log',   '{buchhaltung}',                   '{}',                          '{}'),
      ('ops_fahrtenbuch_entries', '{buchhaltung}',                   '{}',                          '{}'),
      ('ops_fahrtenbuch_vehicles','{buchhaltung}',                   '{}',                          '{}'),
      ('ops_fahrtenbuch_costs',   '{buchhaltung}',                   '{}',                          '{}'),
      ('ops_kunden',              '{vertrieb,technik,support}',      '{vertrieb}',                  '{}'),
      ('ops_kunden_aktivitaeten', '{vertrieb}',                      '{vertrieb}',                  '{}'),
      ('ops_angebote',            '{vertrieb}',                      '{vertrieb}',                  '{}'),
      ('ops_tickets',             '{vertrieb,technik,support}',      '{technik,support}',           '{}'),
      ('ops_ticket_eintraege',    '{vertrieb,technik,support}',      '{technik,support}',           '{}'),
      ('ops_boxen',               '{vertrieb,technik,support}',      '{technik}',                   '{}'),
      ('ops_wartung',             '{technik,support}',               '{technik,support}',           '{}')
    ) as v(tbl, r, w, d)
  loop
    if to_regclass('public.' || m.tbl) is null then
      raise notice 'übersprungen (Tabelle fehlt): %', m.tbl;
      continue;
    end if;
    execute format('alter table %I enable row level security', m.tbl);
    for p in select policyname from pg_policies where schemaname = 'public' and tablename = m.tbl loop
      execute format('drop policy %I on %I', p.policyname, m.tbl);
    end loop;
    rd := format('ops_has_role(variadic %L::text[])', m.r);
    wr := format('ops_has_role(variadic %L::text[])', m.w);
    dl := format('ops_has_role(variadic %L::text[])', m.d);
    execute format('create policy %I on %I for select to authenticated using (%s)', m.tbl || '_r', m.tbl, rd);
    execute format('create policy %I on %I for insert to authenticated with check (%s)', m.tbl || '_i', m.tbl, wr);
    execute format('create policy %I on %I for update to authenticated using (%s) with check (%s)', m.tbl || '_u', m.tbl, wr, wr);
    execute format('create policy %I on %I for delete to authenticated using (%s)', m.tbl || '_d', m.tbl, dl);
  end loop;
end $$;

-- Mitglieder: alle aktiven Mitglieder lesen, nur Admin ändert (Rolle, Farbe, aktiv).
-- Neue Konten entstehen weiter im Supabase-Panel (Signup bleibt AUS) + Insert hier.
drop policy if exists ops_members_read  on ops_members;
drop policy if exists ops_members_admin on ops_members;
create policy ops_members_read on ops_members
  for select to authenticated using (ops_is_member());
create policy ops_members_admin on ops_members
  for all to authenticated using (ops_has_role(variadic '{}'::text[])) with check (ops_has_role(variadic '{}'::text[]));

-- Storage 'wissen' an die Wissensbank-Rollen koppeln.
drop policy if exists wissen_read   on storage.objects;
drop policy if exists wissen_write  on storage.objects;
drop policy if exists wissen_delete on storage.objects;
create policy wissen_read on storage.objects for select to authenticated
  using (bucket_id = 'wissen' and ops_has_role('vertrieb','technik','support'));
create policy wissen_write on storage.objects for insert to authenticated
  with check (bucket_id = 'wissen' and ops_has_role('vertrieb','technik','support'));
create policy wissen_delete on storage.objects for delete to authenticated
  using (bucket_id = 'wissen' and ops_has_role('technik'));

