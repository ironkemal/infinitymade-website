-- ── 1. Rolle + aktiv an ops_members ────────────────────────────────────────
alter table ops_members
  add column if not exists role text not null default 'support'
    check (role in ('admin','vertrieb','technik','support','buchhaltung'));
alter table ops_members
  add column if not exists active boolean not null default true;

-- Bestehende Mitglieder (Kemal, Melih) sind Admins. Nur beim ersten Lauf relevant:
-- danach gibt es bereits Admins und neue Mitglieder behalten ihre Rolle.
do $$
begin
  if not exists (select 1 from ops_members where role = 'admin') then
    update ops_members set role = 'admin';
  end if;
end $$;

-- Mitgliedschaft heißt ab jetzt: Eintrag UND aktiv (Offboarding = active=false).
create or replace function ops_is_member()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from ops_members where id = auth.uid() and active);
$$;

create or replace function ops_role()
returns text language sql stable security definer set search_path = public as $$
  select role from ops_members where id = auth.uid() and active;
$$;

-- admin besteht jede Prüfung.
create or replace function ops_has_role(variadic roles text[])
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from ops_members
    where id = auth.uid() and active and (role = 'admin' or role = any(roles))
  );
$$;

-- Letzten aktiven Admin nicht entfernen/degradieren (sonst sperrt man sich aus).
create or replace function ops_members_guard()
returns trigger language plpgsql as $$
begin
  if (old.role = 'admin' and old.active)
     and (tg_op = 'DELETE' or new.role <> 'admin' or not new.active)
     and (select count(*) from ops_members where role = 'admin' and active and id <> old.id) = 0 then
    raise exception 'Mindestens ein aktiver Admin muss bleiben';
  end if;
  return coalesce(new, old);
end $$;
drop trigger if exists ops_members_guard on ops_members;
create trigger ops_members_guard before update or delete on ops_members
for each row execute function ops_members_guard();

-- ── 2. Kunden & Vertrieb ───────────────────────────────────────────────────
create table if not exists ops_kunden (
  id                uuid primary key default gen_random_uuid(),
  nr                integer generated by default as identity unique,
  name              text not null check (length(trim(name)) > 0),   -- Praxisname
  fachbereich       text not null default 'podologie'
                      check (fachbereich in ('podologie','physio','ergo','logo','interdisziplinaer','sonstiges')),
  stage             text not null default 'lead'
                      check (stage in ('lead','kontakt','demo','angebot','vertrag','installation','live','pausiert','verloren')),
  quelle            text check (quelle in ('website','demo_formular','empfehlung','apify','messe','kaltakquise','bestand','sonstiges')),
  owner             uuid references ops_members(id) on delete set null,   -- verantwortlich
  ansprechpartner   text,
  telefon           text,
  email             text,
  website           text,
  adresse           text,
  plz               text,
  stadt             text,
  standorte         integer,
  mitarbeitende     integer,
  naechster_schritt text,
  naechster_termin  date,
  vertrag_status    text not null default 'offen' check (vertrag_status in ('offen','gesendet','unterschrieben','nicht_noetig')),
  avv_status        text not null default 'offen' check (avv_status in ('offen','gesendet','unterschrieben','nicht_noetig')),
  verloren_grund    text,
  notizen           text not null default '',
  created_by        uuid references ops_members(id) on delete set null,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
create index if not exists ops_kunden_stage_idx  on ops_kunden (stage);
create index if not exists ops_kunden_termin_idx on ops_kunden (naechster_termin) where naechster_termin is not null;

create table if not exists ops_kunden_aktivitaeten (
  id          uuid primary key default gen_random_uuid(),
  kunde_id    uuid not null references ops_kunden(id) on delete cascade,
  art         text not null default 'notiz'
                check (art in ('notiz','anruf','mail','demo','termin','angebot','vertrag','stage')),
  text        text not null default '',
  am          timestamptz not null default now(),
  created_by  uuid references ops_members(id) on delete set null,
  created_at  timestamptz not null default now()
);
create index if not exists ops_kunden_akt_idx on ops_kunden_aktivitaeten (kunde_id, am desc);

-- Angebot wird im Buchhaltungsprogramm erstellt (Lexware/sevDesk); hier nur Status + Link.
create table if not exists ops_angebote (
  id            uuid primary key default gen_random_uuid(),
  kunde_id      uuid not null references ops_kunden(id) on delete cascade,
  nummer        text,
  datum         date not null default current_date,
  gueltig_bis   date,
  status        text not null default 'entwurf'
                  check (status in ('entwurf','gesendet','angenommen','abgelehnt','abgelaufen')),
  leistungen    text not null default '',
  betrag_netto  numeric(12,2),            -- leer lassen, solange Preise nicht festgelegt sind
  link          text,                     -- Lexware/Drive-Link, kein Dokument in der DB
  created_by    uuid references ops_members(id) on delete set null,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index if not exists ops_angebote_kunde_idx on ops_angebote (kunde_id, datum desc);

-- Stage-Wechsel automatisch in die Historie schreiben.
create or replace function ops_kunden_stage_log()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'UPDATE' and new.stage is distinct from old.stage then
    insert into ops_kunden_aktivitaeten (kunde_id, art, text, created_by)
    values (new.id, 'stage', old.stage || ' → ' || new.stage, auth.uid());
  end if;
  return new;
end $$;
drop trigger if exists ops_kunden_stage_log on ops_kunden;
create trigger ops_kunden_stage_log after update on ops_kunden
for each row execute function ops_kunden_stage_log();

