let currentLang = (() => {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (saved && LANGS.includes(saved)) return saved;
  } catch { /* ignore */ }
  return 'de';
})();

const listeners = new Set();
let dbSyncHandler = null;

export function registerLangSync(fn) {
  dbSyncHandler = fn;
}

export function getLang() {
  return currentLang;
}

export function t(key, vars = {}) {
  const table = DICT[currentLang] || DICT.de;
  let str = table[key] ?? DICT.de[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replaceAll(`{${k}}`, String(v ?? ''));
  }
  return str;
}

export function setLang(lang, { syncDb = true } = {}) {
  if (!LANGS.includes(lang)) return;
  const changed = currentLang !== lang;
  currentLang = lang;
  try { localStorage.setItem(LANG_STORAGE_KEY, lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
  applyI18n(document);
  if (changed && syncDb && dbSyncHandler) {
    Promise.resolve(dbSyncHandler(lang)).catch(() => {});
  }
  if (changed) {
    for (const cb of listeners) {
      try { cb(lang); } catch { /* ignore */ }
    }
  }
}

export function onLangChange(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

export function applyI18n(root = document) {
  if (!root) return;
  for (const el of root.querySelectorAll('[data-i18n]')) {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.setAttribute('placeholder', t(key));
  }
  for (const btn of root.querySelectorAll('.lang-btn[data-lang]')) {
    btn.classList.toggle('is-active', btn.getAttribute('data-lang') === currentLang);
  }
}
