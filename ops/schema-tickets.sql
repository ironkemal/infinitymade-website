BEGIN;

-- ── 0. Optionale Box-Identitätsfelder auf ops_customers ─────────────────────
alter table ops_customers
  add column if not exists box_id text unique;

alter table ops_customers
  add column if not exists box_public_key text;

-- ── 1. ops_tickets ──────────────────────────────────────────────────────────
create table if not exists ops_tickets (
  id                uuid primary key default gen_random_uuid(),
  ticket_no         integer generated by default as identity (start with 1001) unique not null,
  customer_id       uuid references ops_customers(id) on delete set null,
  tenant_id         uuid,
  box_name          text,
  source            text not null default 'manual'
                      check (source in ('saas','box','manual')),
  practice_name     text not null default '',
  contact_email     text,
  category          text not null default 'support'
                      check (category in ('bug','support','feature','abrechnung','box','sonstiges')),
  priority          text not null default 'normal'
                      check (priority in ('niedrig','normal','hoch','kritisch')),
  status            text not null default 'neu'
                      check (status in ('neu','in_arbeit','wartet','geloest')),
  subject           text not null check (length(trim(subject)) > 0),
  tech_context      jsonb not null default '{}'::jsonb,
  assigned_to       uuid references ops_members(id) on delete set null,
  linked_todo_id    uuid references ops_todos(id) on delete set null,
  first_response_at timestamptz,
  resolved_at       timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

create index if not exists ops_tickets_status_prio_created_idx
  on ops_tickets (status, priority, created_at desc);

create index if not exists ops_tickets_tenant_idx
  on ops_tickets (tenant_id);

create index if not exists ops_tickets_box_idx
  on ops_tickets (box_name);

drop trigger if exists ops_tickets_touch on ops_tickets;
create trigger ops_tickets_touch
  before update on ops_tickets
  for each row execute function ops_touch_updated_at();

alter table ops_tickets enable row level security;

drop policy if exists ops_tickets_select on ops_tickets;
create policy ops_tickets_select on ops_tickets
  for select to authenticated
  using (ops_is_member());

drop policy if exists ops_tickets_insert on ops_tickets;
create policy ops_tickets_insert on ops_tickets
  for insert to authenticated
  with check (
    ops_has_role(ARRAY['founder','tech','support'])
    or (ops_has_role(ARRAY['sales']) and source = 'manual')
  );

drop policy if exists ops_tickets_update on ops_tickets;
create policy ops_tickets_update on ops_tickets
  for update to authenticated
  using (ops_has_role(ARRAY['founder','tech','support']))
  with check (ops_has_role(ARRAY['founder','tech','support']));

drop policy if exists ops_tickets_delete on ops_tickets;
create policy ops_tickets_delete on ops_tickets
  for delete to authenticated
  using (ops_has_role(ARRAY['founder']));

-- ── 2. ops_ticket_messages ──────────────────────────────────────────────────
create table if not exists ops_ticket_messages (
  id               uuid primary key default gen_random_uuid(),
  ticket_id        uuid not null references ops_tickets(id) on delete cascade,
  sender_type      text not null check (sender_type in ('praxis','staff','system')),
  sender_name      text not null default '',
  sender_member_id uuid references ops_members(id) on delete set null,
  body             text not null check (length(trim(body)) > 0),
  is_internal_note boolean not null default false,
  emailed_at       timestamptz,
  created_at       timestamptz not null default now()
);

create index if not exists ops_ticket_messages_ticket_created_idx
  on ops_ticket_messages (ticket_id, created_at asc);

alter table ops_ticket_messages enable row level security;

drop policy if exists ops_ticket_messages_select on ops_ticket_messages;
create policy ops_ticket_messages_select on ops_ticket_messages
  for select to authenticated
  using (ops_is_member());

drop policy if exists ops_ticket_messages_insert on ops_ticket_messages;
create policy ops_ticket_messages_insert on ops_ticket_messages
  for insert to authenticated
  with check (
    ops_has_role(ARRAY['founder','tech','support'])
    or (ops_has_role(ARRAY['sales']) and is_internal_note = true)
  );

drop policy if exists ops_ticket_messages_delete on ops_ticket_messages;
create policy ops_ticket_messages_delete on ops_ticket_messages
  for delete to authenticated
  using (ops_has_role(ARRAY['founder']));

COMMIT;
